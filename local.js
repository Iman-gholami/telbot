import { recentHistory, BOT_SPEAKER } from "./db.js";
import { normalizePersian } from "./memory.js";

const recentLocalReplies = new Map();
const MAX_CHAT_CACHE = 300;

function rememberPick(chatId, reply) {
  const key = String(chatId);
  const history = recentLocalReplies.get(key) || [];
  history.push(reply);
  recentLocalReplies.set(key, history.slice(-5));
  if (recentLocalReplies.size > MAX_CHAT_CACHE) {
    const first = recentLocalReplies.keys().next().value;
    recentLocalReplies.delete(first);
  }
  return reply;
}

function pick(chatId, items) {
  const values = items.filter(Boolean);
  if (!values.length) return null;
  const used = recentLocalReplies.get(String(chatId)) || [];
  const fresh = values.filter((x) => !used.includes(x));
  const list = fresh.length ? fresh : values;
  return rememberPick(chatId, list[Math.floor(Math.random() * list.length)]);
}

function chance(n) {
  return Math.random() < n;
}

function cleanInput(text) {
  const raw = normalizePersian(text).replace(/ـ/g, "").replace(/\s+/g, " ").trim();
  const plain = raw
    .replace(/[^\p{L}\p{N}\s+\-*/×÷=٪%]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
  return { raw, plain };
}

function contextFor(chatId, currentText, replyToSpeaker, replyToText) {
  const rows = recentHistory(chatId, 8);
  let prior = rows;
  const last = rows.at(-1);
  if (last && normalizePersian(last.text) === normalizePersian(currentText)) prior = rows.slice(0, -1);
  const previousBot = [...prior].reverse().find((x) => x.speaker === BOT_SPEAKER) || null;
  const previousHuman = [...prior].reverse().find((x) => x.speaker !== BOT_SPEAKER) || null;
  const botText = replyToSpeaker === BOT_SPEAKER || /نرگس/.test(String(replyToSpeaker || ""))
    ? String(replyToText || "")
    : String(previousBot?.text || "");
  return {
    previousBot,
    previousHuman,
    botText: normalizePersian(botText),
    replyingToBot: Boolean(replyToText) && (replyToSpeaker === BOT_SPEAKER || /نرگس/.test(String(replyToSpeaker || ""))),
  };
}

function simpleMath(plain) {
  const p = plain.replace(/\s+/g, "");
  let m = p.match(/^(-?\d+(?:\.\d+)?)([+\-*/×÷])(-?\d+(?:\.\d+)?)=?$/);
  if (m) {
    const a = Number(m[1]);
    const b = Number(m[3]);
    const op = m[2];
    let result;
    if (op === "+") result = a + b;
    else if (op === "-") result = a - b;
    else if (op === "*" || op === "×") result = a * b;
    else {
      if (b === 0) return "تقسیم بر صفر؟ منو نکش وسط این جنایت 😂";
      result = a / b;
    }
    if (!Number.isFinite(result)) return null;
    return Number.isInteger(result) ? String(result) : String(Number(result.toFixed(6)));
  }
  m = plain.match(/^(\d+(?:\.\d+)?)\s*(?:درصد|٪|%)\s*(?:از\s*)?(\d+(?:\.\d+)?)$/);
  if (m) return String(Number(((Number(m[1]) / 100) * Number(m[2])).toFixed(6)));
  return null;
}

function isEngineer(speakerName) {
  return speakerName === "مهندس";
}

function isDoctor(speakerName) {
  return speakerName === "خانوم دکتر";
}

function doctorMention(n) {
  return /خانوم دکتر|خانم دکتر|\bدکتر\b/u.test(n);
}

function engineerMention(n) {
  return /مهندس/.test(n);
}

function localAutoReply({ chatId, plain, speakerName }) {
  const engineer = isEngineer(speakerName);
  const doctor = isDoctor(speakerName);

  if (engineer && doctorMention(plain) && /(دوستش دارم|عاشقشم|عاشقش شدم|دلم براش تنگ|قربونش)/.test(plain)) {
    return pick(chatId, [
      "آره مهندس، فکر کنم تا الان کل گروه فهمیده 😂",
      "باشه عاشق‌پیشه، آروم‌تر 😌",
      "خانوم دکتر، این یکی باز شروع کرد 😂",
      "این پرونده دیگه محرمانه نیست مهندس 😭",
    ]);
  }
  if (doctor && engineerMention(plain) && /(خل|احمق|اسکل|دیوونه|رو مخ|اعصاب)/.test(plain)) {
    return pick(chatId, [
      "من هیچی نگفتم‌ها، ولی دفاع هم نمی‌کنم 😂",
      "خانوم دکتر حکم صادر شد ظاهراً 😭",
      "مهندس من جات بودم فعلاً سکوت می‌کردم 😂",
    ]);
  }
  if (engineer && doctorMention(plain) && /(خل|احمق|اسکل|دیوونه)/.test(plain)) {
    return pick(chatId, [
      "اِ اِ، با خانوم دکتر مؤدب مهندس 😂",
      "نه دیگه، اینجا من سمت خانوم دکترم 😌",
      "مهندس داری امتیاز کم می‌کنی حواست هست؟ 😂",
    ]);
  }
  if (doctorMention(plain) && engineerMention(plain) && /(قهر|آشتی|دعوا|دوست)/.test(plain)) {
    return pick(chatId, [
      "من فقط پاپ‌کورنم رو بیارم، ادامه بدین 😂",
      "باز پرونده مهندس و خانوم دکتر باز شد 😌",
      "من وسط این دوتا وکیل هیچ‌کدوم نمی‌شم 😂",
    ]);
  }
  return null;
}

